const char *
icon_sheet_path(int sheet)
{
        if (sheet < 0 || sheet >= ICON_SHEET_COUNT) {
                return NULL;
        }
        return sheet_paths[sheet];
}

const char *
icon_sheet_filename(int sheet)
{
        if (sheet < 0 || sheet >= ICON_SHEET_COUNT) {
                return NULL;
        }
        return sheet_files[sheet];
}

struct IconSrc
icon_src(int index)
{
        struct IconSrc src;
        int col;
        int row;

        if (index < 0 || index >= ICON_COUNT_PER_SHEET) {
                src.sx = 0;
                src.sy = 0;
                src.sw = 0;
                src.sh = 0;
                return src;
        }
        col = index % ICON_ATLAS_COLS;
        row = index / ICON_ATLAS_COLS;
        src.sx = col * ICON_TILE_PX;
        src.sy = row * ICON_TILE_PX;
        src.sw = ICON_TILE_PX;
        src.sh = ICON_TILE_PX;
        return src;
}

int
icon_animal_index(int rank, int class_id)
{
        if (rank < 0 || rank >= ICON_RANK_COUNT) {
                return -1;
        }
        if (class_id < 0 || class_id >= ICON_CLASS_COUNT) {
                return -1;
        }
        return rank * ICON_ATLAS_COLS + class_id;
}

const struct IconRec *
icon_find(const char *id)
{
        size_t i;

        if (id == NULL) {
                return NULL;
        }
        for (i = 0; i < ICON_TOTAL; i++) {
                if (strcmp(icon_table[i].id, id) == 0) {
                        return &icon_table[i];
                }
        }
        return NULL;
}

